// Truthy and Falsy Values
// false: The boolean keyword itself.
// 0: The number zero.
// -0: Negative zero.
// 0n: BigInt zero.
// "" or '' or ``: Any empty string.
// null: The absence of any value.
// undefined: A variable that has been declared but not assigned a value.
// NaN: "Not-a-Number".

let mystery = 5;

if (mystery) {
  console.log("Truthy.");
} else {
  console.log("Falsy.");
}
