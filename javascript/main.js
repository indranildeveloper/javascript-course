function greet(firstName, lastName) {
  console.log(`Hello, ${firstName} ${lastName}`);
}

greet("John", "Doe");

function sumTwo(a, b) {
  console.log(a + b);
}

sumTwo(5, 6);

function sumThree(a, b, c) {
  console.log(a + b + c);
}

sumThree(1, 2, 3);

function divide(a, b) {
  console.log(a / b);
}

divide(1, 5);
divide(5, 1);
